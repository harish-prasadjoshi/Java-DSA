import java.util.*;

public class logicalOp {
    public static void main(String args[]) {

        // AND
        System.out.println((3>2) && (1<11));
        System.out.println((3>2) && (1>11));
        

        // OR
        System.out.println((3>2) || (1<11));
        System.out.println((3>2) || (1>11));
        
        //NOT
        System.out.println(!(3>2));
    


    }
    
}
